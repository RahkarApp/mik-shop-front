export function customerErrorMessage(error, operation = 'default') {
  if (messages[error?.code]) return messages[error.code];
  if (error?.status === 401) return 'برای ادامه، وارد حساب کاربری شوید.';
  if (error?.status === 403) return 'دسترسی به این بخش برای حساب شما ممکن نیست.';
  if (error?.status === 429) return 'تعداد درخواست‌ها زیاد شده است. کمی صبر کنید و دوباره تلاش کنید.';
  const fallback = {
    categories:'دریافت دسته‌بندی‌ها انجام نشد. اتصال اینترنت را بررسی کنید و دوباره تلاش کنید.',
    products:'دریافت محصولات انجام نشد. اتصال اینترنت را بررسی کنید و دوباره تلاش کنید.',
    methods:'دریافت روش‌های ارسال و پرداخت انجام نشد. کمی بعد دوباره تلاش کنید.',
    cart:'بررسی موجودی کالا انجام نشد. سبد شما حفظ شده است؛ کمی بعد دوباره تلاش کنید.',
    quote:'بررسی مبلغ و موجودی سبد انجام نشد. کمی بعد دوباره تلاش کنید.',
    order:'نتیجه ثبت سفارش مشخص نشد. پیش از تلاش دوباره، وضعیت سفارش‌ها را بررسی کنید.',
  };
  return fallback[operation] || 'درخواست انجام نشد. کمی بعد دوباره تلاش کنید.';
}
